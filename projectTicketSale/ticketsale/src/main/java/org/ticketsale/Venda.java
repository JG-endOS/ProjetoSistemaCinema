package org.ticketsale;

public class Venda{
    private Cliente c;
    private Filme f;
    private Sala s;

    public Cliente getC() {
        return c;
    }

    public void setC(Cliente c) {
        this.c = c;
    }

    public Filme getF() {
        return f;
    }

    public void setF(Filme f) {
        this.f = f;
    }

    public Sala getS() {
        return s;
    }

    public void setS(Sala s) {
        this.s = s;
    }
    
}
